using System.Globalization;
using System.Text;
using SpecReport.Core.Model;
using SpecReport.Core.Parsing;

namespace SpecReport.Core.Rendering;

/// <summary>
/// Renders the multi-run report: trend band, flaky list, scenario x run matrix, and a
/// drill-down section per run.
///
/// This and the HTTP panel are the two things the built-in Reqnroll formatter cannot do
/// (SPEC §1.1) - it is strictly single-run.
/// </summary>
internal static class MultiRunHtmlBuilder
{
    public static string BuildBody(MultiRunModel model, string title, AttachmentSpool spool,
                                   ReportOptions options)
    {
        var sb = new StringBuilder();

        Header(sb, model, title);
        Trend(sb, model);
        Flaky(sb, model);
        Matrix(sb, model);
        Runs(sb, model, spool, options);

        sb.Append("<footer>Generated by SpecReport</footer>");
        return sb.ToString();
    }

    private static void Header(StringBuilder sb, MultiRunModel model, string title)
    {
        sb.Append("<header><h1>").Append(E(title)).Append("</h1>");

        var span = model.Runs.Count == 0
            ? "no runs"
            : $"{model.Runs.Count} runs, {model.Series.Count} scenarios";

        sb.Append("<div class=\"subtitle\">").Append(E(span)).Append("</div>");

        var degraded = model.Runs.Where(r => r.Run.Diagnostics.AnyDegradation).ToList();
        if (degraded.Count > 0)
        {
            sb.Append("<div class=\"banner\" role=\"status\"><strong>Incomplete input</strong><span>")
              .Append(E($"{degraded.Count} of {model.Runs.Count} run(s) did not parse cleanly: "))
              .Append(E(string.Join("; ", degraded.Select(r => $"{r.Label} - {r.Run.Diagnostics.Summary()}"))))
              .Append("</span></div>");
        }

        sb.Append("</header>");
    }

    /// <summary>Pass rate per run, oldest to newest. Inline bars rather than a chart library -
    /// the page loads no external anything (SPEC §8.5).</summary>
    private static void Trend(StringBuilder sb, MultiRunModel model)
    {
        if (model.Runs.Count == 0) return;

        sb.Append("<section class=\"feature\"><h2>Trend</h2><div class=\"trend\">");

        foreach (var run in model.Runs)
        {
            var height = Math.Max(2, (int)Math.Round(run.PassRate));
            var failed = run.Counts.GetValueOrDefault(CellStatus.Failed);

            sb.Append("<div class=\"bar\" title=\"")
              .Append(A($"{run.Label}: {run.PassRate}% passed, {failed} failed, {run.TotalScenarios} scenarios"))
              .Append("\"><div class=\"fill")
              .Append(failed > 0 ? " has-failures" : "")
              .Append("\" style=\"height:").Append(height.ToString(CultureInfo.InvariantCulture))
              .Append("%\"></div><span class=\"pct\">")
              .Append(run.PassRate.ToString(CultureInfo.InvariantCulture)).Append("%</span>")
              .Append("<span class=\"lbl\">").Append(E(run.Label)).Append("</span></div>");
        }

        sb.Append("</div></section>");
    }

    private static void Flaky(StringBuilder sb, MultiRunModel model)
    {
        var flaky = model.Flaky.ToList();

        sb.Append("<section class=\"feature\"><h2>Flaky</h2>");

        if (flaky.Count == 0)
        {
            sb.Append("<div class=\"uri\">No scenario changed outcome across these runs.</div>")
              .Append("</section>");
            return;
        }

        // The definition is stated in the report, not just the spec: "flaky" here is a claim
        // about THESE runs, not a statistical property of the scenario.
        sb.Append("<div class=\"uri\">Scenarios with more than one outcome across the runs ")
          .Append("supplied, or which flipped within a single run.</div><table class=\"dt\">")
          .Append("<tr><th>Scenario</th><th>Flips</th><th>Feature</th></tr>");

        foreach (var series in flaky)
        {
            sb.Append("<tr><td>").Append(E(series.Name)).Append("</td><td>")
              .Append(series.FlipCount)
              .Append(series.Cells.Any(c => c.FlakyWithinRun) ? " (+within-run)" : "")
              .Append("</td><td>").Append(E(series.FeatureUri)).Append("</td></tr>");
        }

        sb.Append("</table></section>");
    }

    private static void Matrix(StringBuilder sb, MultiRunModel model)
    {
        sb.Append("<section class=\"feature\"><h2>Scenarios by run</h2>")
          .Append("<div class=\"uri\">Oldest run on the left. ")
          .Append("A blank cell means the scenario did not run - which is not the same as skipped.</div>")
          .Append("<div class=\"matrix-scroll\"><table class=\"matrix\"><tr><th>Scenario</th>");

        foreach (var run in model.Runs)
        {
            sb.Append("<th title=\"").Append(A(run.Label)).Append("\">")
              .Append(E(Shorten(run.Label))).Append("</th>");
        }

        sb.Append("</tr>");

        foreach (var series in model.Series)
        {
            sb.Append("<tr><td class=\"sc\" title=\"").Append(A(series.FeatureUri)).Append("\">")
              .Append(E(series.Name));

            if (series.IsFlaky)
                sb.Append(" <span class=\"flaky\" title=\"Changed outcome\">&#8635;</span>");

            sb.Append("</td>");

            foreach (var cell in series.Cells)
            {
                var status = cell.Status.ToString().ToLowerInvariant();

                sb.Append("<td class=\"cell ").Append(status).Append("\" title=\"")
                  .Append(A(CellTitle(series.Name, cell))).Append("\">")
                  // Glyph AND text, never colour alone (SPEC §8.8). "not run" renders as a
                  // dash, visibly different from a skipped cell's symbol.
                  .Append(CellGlyph(cell.Status))
                  .Append("<span class=\"sr\">").Append(E(status)).Append("</span></td>");
            }

            sb.Append("</tr>");
        }

        sb.Append("</table></div></section>");
    }

    private static void Runs(StringBuilder sb, MultiRunModel model, AttachmentSpool spool,
                             ReportOptions options)
    {
        foreach (var run in model.Runs)
        {
            var view = ViewModelBuilder.Build(run.Run, spool, options);

            sb.Append("<details class=\"scenario run-detail\"><summary>")
              .Append("<span class=\"pill ")
              .Append(run.Counts.GetValueOrDefault(CellStatus.Failed) > 0 ? "failed" : "passed")
              .Append("\">").Append(run.PassRate.ToString(CultureInfo.InvariantCulture))
              .Append("%</span><span class=\"name\"><span class=\"title\">")
              .Append(E(run.Label)).Append("</span>");

            if (run.WasSharded)
            {
                sb.Append("<span class=\"tag\">")
                  .Append(E($"merged from {run.SourceFiles.Count} files")).Append("</span>");
            }

            sb.Append("</span><span class=\"dur\">")
              .Append(E(run.TotalScenarios + " scenarios")).Append("</span></summary>")
              .Append("<div class=\"body\">")
              .Append(HtmlBuilder.BuildBody(view))
              .Append("</div></details>");
        }
    }

    private static string CellTitle(string name, Cell cell)
    {
        if (cell.Status == CellStatus.NotRun) return $"{name}: did not run";

        var suffix = cell.FlakyWithinRun
            ? $" (flaky within run - {cell.AttemptCount} attempts)"
            : string.Empty;

        return $"{name}: {cell.Status.ToString().ToLowerInvariant()}{suffix}";
    }

    private static string CellGlyph(CellStatus status) => status switch
    {
        CellStatus.Passed => "&#10003;",
        CellStatus.Failed => "&#10007;",
        CellStatus.Skipped => "&#8856;",
        CellStatus.Pending => "&#9675;",
        CellStatus.Undefined => "?",
        CellStatus.Ambiguous => "!",
        CellStatus.NotRun => "&ndash;",
        _ => "&middot;"
    };

    private static string Shorten(string label) =>
        label.Length <= 14 ? label : label[..12] + "…";

    private static string E(string? value) => string.IsNullOrEmpty(value)
        ? string.Empty
        : value.Replace("&", "&amp;", StringComparison.Ordinal)
               .Replace("<", "&lt;", StringComparison.Ordinal)
               .Replace(">", "&gt;", StringComparison.Ordinal);

    private static string A(string? value) => E(value)
        .Replace("\"", "&quot;", StringComparison.Ordinal)
        .Replace("'", "&#39;", StringComparison.Ordinal);
}
