using System.Globalization;
using System.Text;

namespace SpecReport.Core.Rendering;

/// <summary>
/// Renders the report body as static HTML.
///
/// The page was originally built entirely in JS from a data island. Server-rendering it instead
/// buys three things worth more than the symmetry:
///   1. The report is readable with JavaScript disabled - it is an archived CI artifact, and a
///      blank page in a locked-down browser is a bad failure mode.
///   2. First paint does not wait on parsing a multi-megabyte island.
///   3. Behaviour like "failed scenarios open by default" becomes a property of the FILE, so it
///      can be proven without driving a browser (SPEC §14.2 forbids assertions that pass
///      without proving the claim).
/// JS is then only interactivity: filtering, search, lightbox.
/// </summary>
internal static class HtmlBuilder
{
    public static string BuildBody(ReportViewModel view)
    {
        var sb = new StringBuilder();

        Header(sb, view);
        Controls(sb, view);

        sb.Append("<div id=\"list\">");
        foreach (var feature in view.Features) Feature(sb, feature);
        sb.Append("<div class=\"empty\" id=\"no-matches\" hidden>No scenarios match these filters.</div>");
        sb.Append("</div>");

        sb.Append("<footer>Generated by SpecReport ").Append(E(view.GeneratorVersion)).Append("</footer>");
        return sb.ToString();
    }

    private static void Header(StringBuilder sb, ReportViewModel view)
    {
        sb.Append("<header><h1>").Append(E(view.Title)).Append("</h1>");

        var when = view.StartedAt is null
            ? "unknown time"
            : DateTimeOffset.Parse(view.StartedAt, CultureInfo.InvariantCulture).LocalDateTime
                .ToString("f", CultureInfo.InvariantCulture);

        sb.Append("<div class=\"subtitle\">").Append(E(when));
        if (view.DurationMs is { } d) sb.Append(" &middot; ").Append(E(Ms(d)));
        sb.Append("</div>");

        // Degradation is stated up front, never swallowed (SPEC §7.1).
        if (view.DegradationBanner is { Length: > 0 } banner)
        {
            sb.Append("<div class=\"banner\" role=\"status\"><strong>Incomplete input</strong><span>")
              .Append(E(banner)).Append("</span></div>");
        }

        sb.Append("<div class=\"summary\"><div class=\"rate\"><div class=\"value\">")
          .Append(view.PassRate.ToString(CultureInfo.InvariantCulture)).Append("%</div>")
          .Append("<div class=\"label\">").Append(view.TotalScenarios).Append(" scenarios</div></div>")
          .Append("<div class=\"counts\">");

        foreach (var status in new[] { "failed", "passed", "skipped", "pending", "undefined", "ambiguous", "unknown" })
        {
            if (!view.Counts.TryGetValue(status, out var n) || n == 0) continue;
            sb.Append("<span class=\"count\"><b>").Append(n).Append("</b><span>")
              .Append(E(status)).Append("</span></span>");
        }

        sb.Append("</div></div>");

        if (view.Metadata.Count > 0)
        {
            sb.Append("<div class=\"meta\">");
            foreach (var entry in view.Metadata)
            {
                sb.Append("<span><b>").Append(E(entry.Label)).Append(": </b>")
                  .Append(E(entry.Value)).Append("</span>");
            }
            sb.Append("</div>");
        }

        sb.Append("</header>");
    }

    private static void Controls(StringBuilder sb, ReportViewModel view)
    {
        sb.Append("<div class=\"controls\">")
          .Append("<input type=\"search\" id=\"q\" placeholder=\"Search scenarios and steps&hellip;\" ")
          .Append("aria-label=\"Search scenarios and steps\">");

        foreach (var status in new[] { "all", "failed", "passed", "skipped" })
        {
            sb.Append("<button type=\"button\" class=\"chip\" data-status=\"").Append(status)
              .Append("\" aria-pressed=\"").Append(status == "all" ? "true" : "false").Append("\">")
              .Append(status).Append("</button>");
        }

        if (view.AllTags.Count > 0)
        {
            sb.Append("<select id=\"tag\" aria-label=\"Filter by tag\"><option value=\"\">All tags</option>");
            foreach (var tag in view.AllTags)
                sb.Append("<option value=\"").Append(A(tag)).Append("\">@").Append(E(tag)).Append("</option>");
            sb.Append("</select>");
        }

        sb.Append("</div>");
    }

    private static void Feature(StringBuilder sb, FeatureView feature)
    {
        sb.Append("<section class=\"feature\" data-feature=\"").Append(A(feature.Uri)).Append("\">")
          .Append("<h2><span class=\"kw\">").Append(E(feature.Keyword)).Append(": </span>")
          .Append(E(feature.Name)).Append("</h2>")
          .Append("<div class=\"uri\">").Append(E(feature.Uri)).Append("</div>");

        foreach (var group in feature.Groups)
        {
            if (group.RuleName is { Length: > 0 } rule)
            {
                sb.Append("<div class=\"rule\"><h3><span class=\"kw\">Rule: </span>")
                  .Append(E(rule)).Append("</h3>");
                foreach (var scenario in group.Scenarios) Scenario(sb, scenario);
                sb.Append("</div>");
            }
            else
            {
                foreach (var scenario in group.Scenarios) Scenario(sb, scenario);
            }
        }

        sb.Append("</section>");
    }

    private static void Scenario(StringBuilder sb, ScenarioView scenario)
    {
        // Searchable haystack in an attribute so filtering needs no data island.
        var haystack = new StringBuilder(scenario.Name.ToLowerInvariant());
        foreach (var step in scenario.Steps) haystack.Append(' ').Append(step.Text.ToLowerInvariant());

        // Failures open, passes closed. Nobody opens a report to admire the passes (SPEC §4.2),
        // and because this is a real attribute it is provable without a browser.
        sb.Append("<details class=\"scenario\" data-status=\"").Append(A(scenario.Status))
          .Append("\" data-tags=\"").Append(A(string.Join(" ", scenario.Tags)))
          .Append("\" data-text=\"").Append(A(haystack.ToString())).Append('"');
        if (scenario.Status == "failed") sb.Append(" open");
        sb.Append('>');

        sb.Append("<summary><span class=\"pill ").Append(A(scenario.Status)).Append("\">")
          .Append(E(scenario.Status)).Append("</span><span class=\"name\"><span class=\"title\">")
          .Append(E(scenario.Name)).Append("</span>");

        if (scenario.FlakyWithinRun)
            sb.Append("<span class=\"flaky\" title=\"Failed then passed within this run\">&#8635; flaky</span>");

        foreach (var tag in scenario.Tags)
            sb.Append("<span class=\"tag\">@").Append(E(tag)).Append("</span>");

        if (scenario.Status == "failed" && scenario.FailureSummary is { Length: > 0 } why)
            sb.Append("<span class=\"why\">").Append(E(why)).Append("</span>");

        sb.Append("</span><span class=\"dur\">").Append(E(Ms(scenario.DurationMs)))
          .Append("</span></summary><div class=\"body\">");

        if (scenario.ExampleValues.Count > 0)
        {
            sb.Append("<div class=\"examples\">Example: <code>");
            sb.Append(E(string.Join("  ", scenario.ExampleValues.Select(kv => kv.Key + "=" + kv.Value))));
            sb.Append("</code></div>");
        }

        foreach (var step in scenario.Steps) Step(sb, step);

        if (scenario.OutsideStepEvidence.Count > 0)
        {
            sb.Append("<div class=\"examples\">Captured outside any step</div>");
            Evidence(sb, scenario.OutsideStepEvidence);
        }

        foreach (var attempt in scenario.EarlierAttempts)
        {
            sb.Append("<details class=\"scenario\"><summary><span class=\"pill ")
              .Append(A(attempt.Status)).Append("\">").Append(E(attempt.Status))
              .Append("</span><span class=\"name\"><span class=\"title\">Attempt ")
              .Append(attempt.AttemptNumber + 1).Append(" (retried)</span></span></summary>")
              .Append("<div class=\"body\">");
            foreach (var step in attempt.Steps) Step(sb, step);
            sb.Append("</div></details>");
        }

        sb.Append("</div></details>");
    }

    private static void Step(StringBuilder sb, StepView step)
    {
        sb.Append("<div class=\"step ").Append(A(step.Status));
        if (step.Kind == "hook") sb.Append(" hook");
        sb.Append("\">");

        // Status is carried by glyph AND text. The word is visually hidden but present for
        // assistive tech and text search - never colour alone (SPEC §8.8).
        sb.Append("<span class=\"glyph\" aria-hidden=\"true\">").Append(Glyph(step.Status)).Append("</span>")
          .Append("<span class=\"sr\">").Append(E(step.Status)).Append("</span>");

        if (step.Kind == "gherkin")
            sb.Append("<span class=\"kw\">").Append(E(step.Keyword)).Append("</span>");

        sb.Append("<span class=\"txt\">").Append(E(step.Text)).Append("</span>");

        if (step.IsBackground) sb.Append("<span class=\"bg-tag\">background</span>");
        if (step.StatusInferred)
            sb.Append("<span class=\"inferred\" title=\"Not reported by the run - inferred because the stream ended early\">inferred</span>");

        sb.Append("<span class=\"dur\">")
          .Append(step.DurationMs > 0 ? E(Ms(step.DurationMs)) : "")
          .Append("</span></div>");

        if (step.ErrorMessage is { Length: > 0 })
        {
            sb.Append("<div class=\"err\">");
            if (step.ErrorType is { Length: > 0 })
                sb.Append("<span class=\"type\">").Append(E(step.ErrorType)).Append(": </span>");
            sb.Append(E(step.ErrorMessage));

            if (step.ErrorStack is { Length: > 0 })
            {
                sb.Append("<details><summary>stack trace</summary><pre>")
                  .Append(E(step.ErrorStack)).Append("</pre></details>");
            }
            sb.Append("</div>");
        }

        if (step.DataTable is { Count: > 0 } table)
        {
            sb.Append("<table class=\"dt\">");
            for (var r = 0; r < table.Count; r++)
            {
                sb.Append("<tr>");
                var cell = r == 0 ? "th" : "td";
                foreach (var value in table[r])
                    sb.Append('<').Append(cell).Append('>').Append(E(value)).Append("</").Append(cell).Append('>');
                sb.Append("</tr>");
            }
            sb.Append("</table>");
        }

        if (step.DocString is { Length: > 0 })
            sb.Append("<pre class=\"ds\">").Append(E(step.DocString)).Append("</pre>");

        if (step.Evidence.Count > 0) Evidence(sb, step.Evidence);
    }

    private static void Evidence(StringBuilder sb, List<EvidenceView> items)
    {
        sb.Append("<div class=\"ev\">");

        var shots = items.Where(e => e.Kind == "screenshot").ToList();
        if (shots.Count > 0)
        {
            sb.Append("<div class=\"shots\">");
            foreach (var shot in shots)
            {
                var src = shot.DataUri ?? shot.AssetPath;
                if (src is null) continue;
                sb.Append("<img loading=\"lazy\" alt=\"").Append(A(shot.FileName ?? "Screenshot"))
                  .Append("\" src=\"").Append(A(src)).Append("\">");
            }
            sb.Append("</div>");
        }

        foreach (var http in items.Where(e => e.Kind == "http").Select(e => e.Http).OfType<HttpView>())
            Http(sb, http);

        foreach (var text in items.Where(e => e.Kind is "log" or "json"))
        {
            var content = text.Text ?? $"({Bytes(text.SizeBytes)} not inlined)";
            sb.Append("<pre class=\"log\">").Append(E(content)).Append("</pre>");
        }

        var files = items.Where(e => e.Kind == "file").ToList();
        if (files.Count > 0)
        {
            sb.Append("<div class=\"ev-badges\">");
            foreach (var file in files)
            {
                sb.Append("<span class=\"ev-badge\">").Append(E(file.FileName ?? "file"))
                  .Append(" &middot; ").Append(E(Bytes(file.SizeBytes))).Append("</span>");
            }
            sb.Append("</div>");
        }

        sb.Append("</div>");
    }

    private static void Http(StringBuilder sb, HttpView http)
    {
        sb.Append("<div class=\"http\"><div class=\"line\"><span class=\"method\">")
          .Append(E(http.Method)).Append("</span><span class=\"url\">").Append(E(http.Url))
          .Append("</span>");

        if (http.Status is { } status)
        {
            sb.Append("<span class=\"code c").Append(status.ToString(CultureInfo.InvariantCulture)[0])
              .Append("\">").Append(status);
            if (http.Reason is { Length: > 0 }) sb.Append(' ').Append(E(http.Reason));
            sb.Append("</span>");
        }

        sb.Append("<span class=\"ms\">").Append(E(Ms(http.DurationMs))).Append("</span></div>");

        if (http.Error is { Length: > 0 })
            sb.Append("<div class=\"part\"><h4>Error</h4><pre>").Append(E(http.Error)).Append("</pre></div>");

        Part(sb, "Request", http.RequestHeaders, http.RequestBody, http.RequestBodyTruncated);

        if (http.Status is not null)
            Part(sb, "Response", http.ResponseHeaders, http.ResponseBody, http.ResponseBodyTruncated);

        // What was withheld is always shown. A quietly incomplete request is worse than an
        // obviously redacted one (SPEC §5.2).
        if (http.Redactions.Count > 0)
        {
            sb.Append("<div class=\"part\"><span class=\"marker\">redacted: ")
              .Append(E(string.Join(", ", http.Redactions))).Append("</span></div>");
        }

        sb.Append("</div>");
    }

    private static void Part(
        StringBuilder sb, string title, Dictionary<string, string> headers, string? body, bool truncated)
    {
        sb.Append("<div class=\"part\"><h4>").Append(E(title)).Append("</h4>");

        if (headers.Count > 0)
        {
            sb.Append("<dl>");
            foreach (var (name, value) in headers)
            {
                var redacted = value.Contains("redacted", StringComparison.OrdinalIgnoreCase);
                sb.Append("<dt>").Append(E(name)).Append("</dt><dd")
                  .Append(redacted ? " class=\"redacted\"" : "").Append('>')
                  .Append(E(value)).Append("</dd>");
            }
            sb.Append("</dl>");
        }

        if (body is { Length: > 0 })
        {
            sb.Append("<pre>").Append(E(body)).Append("</pre>");
            if (truncated) sb.Append("<span class=\"marker\">body truncated</span>");
        }

        sb.Append("</div>");
    }

    private static string Glyph(string status) => status switch
    {
        "passed" => "&#10003;",
        "failed" => "&#10007;",
        "skipped" => "&#8856;",
        "pending" => "&#9675;",
        "undefined" => "?",
        "ambiguous" => "!",
        _ => "&middot;"
    };

    private static string Ms(double value)
    {
        if (value < 1000) return Math.Round(value).ToString(CultureInfo.InvariantCulture) + " ms";
        if (value < 60000) return (value / 1000).ToString("0.00", CultureInfo.InvariantCulture) + " s";
        return Math.Floor(value / 60000).ToString(CultureInfo.InvariantCulture) + "m " +
               Math.Round(value % 60000 / 1000).ToString(CultureInfo.InvariantCulture) + "s";
    }

    private static string Bytes(long n) => n switch
    {
        < 1024 => n + " B",
        < 1048576 => (n / 1024.0).ToString("0.0", CultureInfo.InvariantCulture) + " KB",
        _ => (n / 1048576.0).ToString("0.0", CultureInfo.InvariantCulture) + " MB"
    };

    /// <summary>
    /// Escapes element text. Every value from the run passes through here or <see cref="A"/> -
    /// a scenario named with a closing script tag must never become markup (SPEC §8.6).
    /// </summary>
    private static string E(string? value) => string.IsNullOrEmpty(value)
        ? string.Empty
        : value.Replace("&", "&amp;", StringComparison.Ordinal)
               .Replace("<", "&lt;", StringComparison.Ordinal)
               .Replace(">", "&gt;", StringComparison.Ordinal);

    /// <summary>Escapes an attribute value; quotes matter here as well as angle brackets.</summary>
    private static string A(string? value) => E(value)
        .Replace("\"", "&quot;", StringComparison.Ordinal)
        .Replace("'", "&#39;", StringComparison.Ordinal);
}
